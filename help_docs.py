def get_error_info(error_name):
    """Возвращает описание и решение по названию ошибки."""
    return ERRORS.get(error_name, None)

def search_errors(query):
    """Ищет ошибки по ключевому слову в названии, описании или решении."""
    results = []
    query_lower = query.lower()
    for name, data in ERRORS.items():
        if (query_lower in name.lower() or
            query_lower in data['description'].lower() or
            query_lower in data['solution'].lower()):
            results.append((name, data))
    return results
